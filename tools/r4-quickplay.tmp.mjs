import fs from 'node:fs';
import * as Ar from '../frontend/v5/core/archive.js';
import * as Gm from '../frontend/v5/core/game.js';
import { playThrough } from '../test/v5-bot.mjs';
const read = (f) => fs.readFileSync('frontend/v5/data/' + f, 'utf8'); const texts = {}; for (const s of Ar.SOURCES) { texts[s.id] = read(s.file); } texts.edition = read('edition-present.txt'); texts.drafts = read('drafts-unsent.txt');
const ar = Ar.createArchive(texts); const g = Gm.createGame(ar);
const bot = await playThrough(g, { optional: process.argv[2] !== 'min' });
console.log('beats', [...new Set(bot.beats)].join(' '));
console.log('final', g.s.beat, 'stuck', JSON.stringify(bot.stuck), 'replanned', bot.replanned.length, 't', bot.t.toFixed(0));
console.log(JSON.stringify(bot.marks));

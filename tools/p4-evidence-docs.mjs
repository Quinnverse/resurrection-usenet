// Developer tool: turns a CI browser-job log into docs/p4-evidence/ images and the two evidence pages.
//   gh api repos/<owner>/<repo>/actions/jobs/<job id>/logs > job.log
//   node tools/p4-evidence-docs.mjs job.log <run url> <commit>
// The spec prints `P4_SHOT <name> <base64 jpeg>` and `P4_REC <label> <nnn> <urlencoded line> <base64 jpeg>` in CI.
import fs from 'node:fs';
import path from 'node:path';

const [logFile, runUrl, commit] = process.argv.slice(2);
if (!logFile) { console.error('usage: node tools/p4-evidence-docs.mjs <job.log> [run url] [commit]'); process.exit(2); }
const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'docs', 'p4-evidence');
fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(path.join(dir, 'record'), { recursive: true });

const shots = [], rec = [];
let times = '';
for (const line of fs.readFileSync(logFile, 'utf8').split('\n')) {
  const i = line.indexOf('P4_SHOT ');
  if (i >= 0) { const p = line.slice(i).trim().split(' '); fs.writeFileSync(path.join(dir, p[1] + '.jpg'), Buffer.from(p[2], 'base64')); shots.push(p[1]); }
  const j = line.indexOf('P4_REC ');
  if (j >= 0) { const p = line.slice(j).trim().split(' '); const f = `${p[1]}-${p[2]}.jpg`; fs.writeFileSync(path.join(dir, 'record', f), Buffer.from(p[4], 'base64')); rec.push([f, decodeURIComponent(p[3])]); }
  const k = line.indexOf('P4_TIME ');
  if (k >= 0) { times = line.slice(k + 8).trim(); }
}


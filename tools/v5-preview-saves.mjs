// Writes frontend/v5/data/preview-saves.json: one save at the start of every beat, made by playing the core with the
// scripted bot (the same method the browser tests use). The game opens one of them with /v5/?preview=<beat> so a
// reviewer can look at the train, the coast ride, the lighthouse, the porch at night, the 2004 beach or the final snow
// without playing from the start. Opening a preview never touches the real save.
//
//   node tools/v5-preview-saves.mjs            write the file
//   node tools/v5-preview-saves.mjs --check    exit 1 if the file is not what the current code produces
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as Gm from '../frontend/v5/core/game.js';
import { loadArchive } from './v5-playthrough.mjs';
import { playThrough } from '../test/v5-bot.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FILE = path.join(root, 'frontend', 'v5', 'data', 'preview-saves.json');

export async function makeSaves() {
  const g = Gm.createGame(loadArchive()); const saves = {};
  // besides one save per beat: "snow", the moment the final lines begin at the end of the new pier (winter, lamp lit, planks laid)
  await playThrough(g, { step: (input) => { const ev = Gm.tick(g, 1 / 30, input); if (!saves[g.s.beat]) { saves[g.s.beat] = Gm.serialize(g); } if (!saves.snow && g.rt.dialog && g.rt.dialog.id === 'c7.final') { saves.snow = Gm.serialize(g); } return ev; } });
  const ordered = {}; Gm.BEATS.forEach((b) => { if (saves[b]) { ordered[b] = saves[b]; } }); if (saves.snow) { ordered.snow = saves.snow; }
  return { version: 1, note: 'Generated by tools/v5-preview-saves.mjs. One save at the start of each beat; used only by ?preview= and ?bench=.', saves: ordered };
}
const text = (o) => JSON.stringify(o) + '\n';

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const made = text(await makeSaves());
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
    if (have !== made) { console.error('preview-saves.json is out of date: run node tools/v5-preview-saves.mjs'); process.exit(1); }
    console.log('preview-saves.json is current');
  } else { fs.writeFileSync(FILE, made); console.log('wrote', path.relative(root, FILE), made.length, 'bytes'); }
}
